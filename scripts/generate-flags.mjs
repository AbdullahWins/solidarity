// Generates constants/flags.ts: SVG strings (3:2) for every ISO code used in
// constants/country-iso.ts. Only the flags we need end up in the app bundle;
// country-flag-icons itself is a dev dependency.
//
// Run: npm run flags
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const src = readFileSync(join(root, "constants/country-iso.ts"), "utf8");
const codes = [...new Set([...src.matchAll(/:\s*"([A-Z]{2})"/g)].map((m) => m[1]))].sort();

const flagsDir = join(dirname(require.resolve("country-flag-icons/package.json")), "string", "3x2");
const lines = [];
const missing = [];
for (const code of codes) {
  let svg;
  try {
    const js = readFileSync(join(flagsDir, `${code}.js`), "utf8");
    svg = js.match(/export default '([\s\S]*)'/)[1];
  } catch {
    missing.push(code);
    continue;
  }
  lines.push(`  ${code}: ${JSON.stringify(svg.replace(/\\'/g, "'"))},`);
}

writeFileSync(
  join(root, "constants/flags.ts"),
  `// GENERATED by scripts/generate-flags.mjs from country-flag-icons (MIT). Do not edit.\n` +
    `export const FLAG_SVGS: Record<string, string> = {\n${lines.join("\n")}\n};\n`
);
console.log(`wrote ${lines.length} flags${missing.length ? `, missing: ${missing.join(", ")}` : ""}`);
